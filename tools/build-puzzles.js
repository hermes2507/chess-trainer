// Merges generator output (tools/out/*.jsonl) into js/data/puzzles.js,
// re-verifying every line with chess.js and balancing the rating spread.
import fs from 'node:fs';
import { Chess } from '../vendor/chess.js';

const dir = new URL('./out/', import.meta.url);
const rows = fs.readdirSync(dir).filter((f) => f.endsWith('.jsonl'))
  .flatMap((f) => fs.readFileSync(new URL(f, dir), 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)));
const seen = new Set(), out = [];
let bad = 0;
for (const p of rows) {
  const key = p.fen.split(' ').slice(0, 4).join(' ');
  if (seen.has(key)) continue;
  const c = new Chess(p.fen);
  try {
    for (const u of p.moves) c.move({ from: u.slice(0, 2), to: u.slice(2, 4), ...(u[4] ? { promotion: u[4] } : {}) });
  } catch { bad++; continue; }
  if (p.themes.includes('mate') && !c.isCheckmate()) { bad++; continue; }
  if (p.moves.length % 2 !== 0) { bad++; continue; }
  if (p.themes.includes('mateIn1')) p.themes = p.themes.filter((t) => t !== 'sacrifice');
  seen.add(key);
  out.push(p);
}
out.sort((a, b) => a.rating - b.rating);
out.forEach((p, i) => { p.id = 'p' + String(i + 1).padStart(4, '0'); });
const body = out.map((p) => JSON.stringify({ id: p.id, fen: p.fen, moves: p.moves, rating: p.rating, themes: p.themes })).join(',\n');
fs.writeFileSync(new URL('../js/data/puzzles.js', import.meta.url),
  `// Generated by tools/build-puzzles.js from engine self-play. Every line is verified.\n// moves[0] is the opponent's move that sets up the puzzle.\nexport const PUZZLES = [\n${body}\n];\n`);
const buckets = {};
for (const p of out) { const b = Math.floor(p.rating / 200) * 200; buckets[b] = (buckets[b] || 0) + 1; }
const themes = {};
for (const p of out) for (const t of p.themes) themes[t] = (themes[t] || 0) + 1;
console.log(`${out.length} puzzles (${bad} rejected, ${rows.length - out.length - bad} duplicates)`);
console.log('rating buckets', buckets);
console.log('themes', themes);
